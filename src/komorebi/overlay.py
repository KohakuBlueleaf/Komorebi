"""Overlays, the host side: a program's overlays and slots, the builder that compiles a
part with the runtime's own commands as position-independent code and checks it, and
the overlay area and DRAM image the session writes. The device side is km_overlay.hpp.
"""

import functools
import hashlib
import json
import os
import re
import shlex
import subprocess
from dataclasses import dataclass, field, replace
from pathlib import Path

import numpy as np

from komorebi import _env, abi
from komorebi.errors import ProgramError

KERNELS = ("reader", "writer", "compute")
# The five parts of an overlay, in the order of the area's tables, by kernel and by
# the runtime's build target of each core.
PARTS = ("reader", "writer", "unpack", "math", "pack")
KERNEL_PARTS = {
    "reader": ("reader",),
    "writer": ("writer",),
    "compute": ("unpack", "math", "pack"),
}
TARGETS = {
    "brisc": "reader",
    "ncrisc": "writer",
    "trisc0": "unpack",
    "trisc1": "math",
    "trisc2": "pack",
}
KERNEL_CLASSES = {
    "reader": "km::Reader",
    "writer": "km::Writer",
    "compute": "km::Compute",
}
FUNCTION = "km_overlay"  # the part's function: (kernel object, const argument&)
PROGRAM_FUNCTION = "km_program_part"  # a program's part: its km_program (entry hpp)
MESSAGE_FUNCTION = "km_message_part"  # a handler's part: its km_message (entry hpp)
COMPILE_ARGS = "-DKERNEL_COMPILE_TIME_ARGS="  # a program's part gives its own
OVERLAY = re.compile(
    r"constexpr\s+uint32_t\s+kOverlay(\w+)\s*=\s*(0x[0-9A-Fa-f]+|\d+)u?;"
)
ALIGN = 64  # slots, images and DRAM copies are whole 64-byte lines
# The service overlay's slot a class's build reserves on a one-island session: built
# 8,640 B (8,840 B with KM_CHECK_NOC_SOURCES), rounded up to 9 KiB.
SERVICE_SLOT_MOST = 9216
# On an island session (KM_PAGE_LINKS): the largest island load logged, 41,856 B (two
# cards; 39,552 B split in two, 39,512 in three), and 1,152 B of margin: 42 KiB.
ISLAND_SERVICE_SLOT_MOST = 43008
LINK_BASE = 0x100000  # the first of the two links; the second is one line above
LINK_LENGTH = 1 << 20
ENTRY = "km_overlay_entry"
INCLUDED = re.compile(r'^# \d+ "([^"<]+)"', re.M)  # a preprocessed file's line markers
# File-static state of the math library that a part keeps its own copy of: the entry
# marks it unknown (km_overlay_entry.hpp), so a copy is not a second runtime state.
RESETS = (
    "_ZN7ckernel4mathL16src_zero_flag_hwE",
    "_ZN7ckernel4mathL22src_zero_flag_srca_fmtE",
    "_ZN7ckernel4mathL22src_zero_flag_srcb_fmtE",
)
# The build's constant tables of the buffers' formats (genfiles.cpp, `constexpr`): a
# part built against the kernel has the same bytes, a copy that is not state.
TABLES = (
    "_ZL17unpack_src_format",
    "_ZL17unpack_dst_format",
    "_ZL15pack_src_format",
    "_ZL15pack_dst_format",
)
DROPPED_COMPILE = ("-MMD",)
DROPPED_DEFINE = "-DFULL_KERNEL_NAME="
DROPPED_LINK = ("-T", "-Wl,--just-symbols=", "-Wl,--emit-relocs")
SCRIPT = """\
OUTPUT_ARCH(riscv)
ENTRY(km_overlay_entry)
MEMORY {{ SLOT (rwx) : ORIGIN = {base:#x}, LENGTH = {length:#x} }}
SECTIONS
{{
  .text : {{ KEEP(*(.km_overlay_entry)) *(.text .text.*) }} > SLOT
  .rodata : {{ *(.rodata .rodata.* .srodata .srodata.*) }} > SLOT
  .got : {{ *(.got .got.*) }} > SLOT
  .data : {{ *(.data .data.* .sdata .sdata.*) . = ALIGN(4); }} > SLOT
  .bss (NOLOAD) : {{
    __km_overlay_bss_start = .;
    *(.bss .bss.* .sbss .sbss.* COMMON)
    . = ALIGN(4);
    __km_overlay_bss_end = .;
  }} > SLOT
  /DISCARD/ : {{ *(.eh_frame*) *(.note*) *(.init_array*) *(.fini_array*) }}
}}
"""
WRAPPER = """\
// Generated by the overlay builder: part {part} of overlay {name}.
#include "komorebi/device/km_overlay_part.hpp"
#include "{source}"
#include "komorebi/device/km_overlay_entry.hpp"
"""


class OverlayError(ProgramError):
    """An overlay part the builder refuses: it would not run as built. Nothing was
    loaded."""


@functools.cache
def constants():
    """The overlay area's constants (km_overlay.hpp)."""
    path = _env.include_directory() / "komorebi" / "device" / "km_overlay.hpp"
    return abi.constants(path, known=abi.headers().constants)


def service():
    """The runtime's service overlay: the reader part that serves PUSH, PULL and COPY,
    in every run under the last number; a core loads it on its first such command."""
    include = _env.include_directory()
    if include is None:
        raise FileNotFoundError("the native kernels are not beside the package")
    source = include.parent / "kernels" / "service_reader.cpp"
    return Overlay("service", constants()["kOverlayService"], {"reader": source})


def overlays_from_header(path):
    """`constexpr uint32_t kOverlayName = n;` lines of a header as {"name": n}."""
    found = {}
    for name, value in OVERLAY.findall(Path(path).read_text()):
        snake = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
        found[snake] = int(value, 0)
    return found


@dataclass(frozen=True)
class Overlay:
    """An overlay of a program: its number (1 to 63) and a source per kernel that has a
    part ("reader", "writer", "compute"); `defines` go to its parts' builds only. A
    program's overlay (`program`) calls km_program with its own `compile_args`; a
    dynamic handler's (`message`, a compute part) calls km_message."""

    name: str
    number: int
    sources: dict
    defines: dict = field(default_factory=dict)
    program: bool = False
    compile_args: dict = field(default_factory=dict)  # kernel -> [words]
    message: bool = False

    def __post_init__(self):
        most = constants()["kOverlaysMax"] - 1
        if not 1 <= self.number <= most:
            raise ValueError(f"overlay {self.name} = {self.number}: not in 1..{most}")
        unknown = set(self.sources) - set(KERNELS)
        if unknown or not self.sources:
            raise ValueError(
                f"overlay {self.name}: parts for {sorted(self.sources)}; a part is "
                f"one of {KERNELS}"
            )
        missing = [str(p) for p in self.sources.values() if not Path(p).is_file()]
        if missing:
            raise FileNotFoundError(f"overlay {self.name}: no source {missing}")
        if self.message and set(self.sources) != {"compute"}:
            raise ValueError(f"handler {self.name}: its body is one compute part")

    def parts(self):
        """[(kernel, part)] of the overlay, in the area's part order."""
        return [
            (kernel, part)
            for kernel in KERNELS
            if kernel in self.sources
            for part in KERNEL_PARTS[kernel]
        ]


def declare(name, parts, number, defines=None):
    """An Overlay from `parts`: a folder holding reader.cpp, writer.cpp, compute.cpp
    (any of them), or a dict {kernel: source}."""
    if isinstance(parts, dict):
        sources = {kernel: Path(path) for kernel, path in parts.items()}
    else:
        folder = Path(parts)
        sources = {
            kernel: folder / f"{kernel}.cpp"
            for kernel in KERNELS
            if (folder / f"{kernel}.cpp").is_file()
        }
        if not sources:
            raise FileNotFoundError(
                f"overlay {name}: {folder} holds no reader.cpp, writer.cpp, compute.cpp"
            )
    return Overlay(name, int(number), sources, dict(defines or {}))


@dataclass(frozen=True)
class Recipe:
    """One core's build of a persistent kernel, as the runtime ran it: its ELF, the
    compiler, levels, flags, include and define arguments (Launch.recipes())."""

    target: str
    elf: Path
    compiler: tuple
    opt: str
    cflags: tuple
    includes: tuple
    lflags: tuple
    link_opt: str
    defines: tuple

    @classmethod
    def from_native(cls, row):
        target, elf, gpp, opt, cflags, includes, lflags, link_opt, *defines = row
        compiler = [word for word in shlex.split(gpp) if word.endswith("g++")]
        if len(compiler) != 1:
            raise OverlayError(f"{target}: no compiler in the runtime's {gpp!r}")
        return cls(
            target,
            Path(elf),
            tuple(compiler),
            opt,
            tuple(shlex.split(cflags)),
            tuple(shlex.split(includes)),
            tuple(shlex.split(lflags)),
            link_opt,
            tuple(defines),
        )

    def provided(self):
        """The PROVIDE lines of the kernel's link script: symbols such as the
        instruction buffer, which the kernel's ELF lacks when it never used them."""
        scripts = [Path(word[2:]) for word in self.lflags if word.startswith("-T")]
        lines = []
        for script in scripts:
            if not script.is_absolute():
                script = self.elf.parent / script
            lines += [
                line.strip()
                for line in script.read_text().splitlines()
                if line.strip().startswith("PROVIDE(")
            ]
        return "".join(f"{line}\n" for line in lines)

    def tool(self, name):
        """A binutils program beside the compiler (readelf, objcopy, gcc-nm)."""
        return self.compiler[0][: -len("g++")] + name

    def compile_command(self, source, out, defines, action="-c", compile_args=None):
        """The runtime's compile of this core, position-independent, with `defines`
        ({name: value}); `action` -c or -E; `compile_args` (a list) in place of the
        kernel's. Include folders relative to the ELF's folder are made absolute."""
        folder = self.elf.parent
        includes = []
        for word in self.includes:
            path = word[2:] if word.startswith("-I") else None
            if path is not None and not Path(path).is_absolute():
                word = f"-I{(folder / path).resolve()}"
            includes.append(word)
        dropped = (
            (DROPPED_DEFINE,)
            if compile_args is None
            else (DROPPED_DEFINE, COMPILE_ARGS)
        )
        own = (
            []
            if not compile_args
            else [COMPILE_ARGS + ",".join(map(str, compile_args))]
        )
        return [
            *self.compiler,
            f"-{self.opt}",
            *(word for word in self.cflags if word not in DROPPED_COMPILE),
            *includes,
            *(word for word in self.defines if not word.startswith(dropped)),
            *own,
            "-fpie",
            "-fvisibility=hidden",
            *(f"-D{name}={value}" for name, value in defines.items()),
            action,
            str(source),
            "-o",
            str(out),
        ]

    def link_command(self, obj, script, out):
        """The runtime's link of this core with the builder's script, against the
        persistent kernel's symbols."""
        return [
            *self.compiler,
            f"-{self.link_opt}",
            *(word for word in self.lflags if not word.startswith(DROPPED_LINK)),
            f"-T{script}",
            f"-Wl,--just-symbols={self.elf}",
            str(obj),
            "-o",
            str(out),
        ]


@dataclass(frozen=True)
class Linked:
    """What the checks read of one link of a part: its base, the entry symbol's
    address (None: none), relocation sections left, the symbols it defines {name:
    (value, kind, binding)}, the names the object refers to, its extent and image."""

    base: int
    entry: int | None
    relocations: tuple
    symbols: dict
    undefined: tuple
    extent: int
    image: bytes


@dataclass(frozen=True)
class Persistent:
    """The persistent kernel a part links against: its .text range and its defined
    symbols {name: (value, kind, binding)}."""

    text: tuple
    symbols: dict


def check(name, part, first, second, persistent, slot_bytes=None):
    """Refuses a part (OverlayError) that has no entry at its first byte, relocations
    left, a call into the persistent kernel's text, its own copy of the runtime's
    state, two links at two addresses that differ, or more bytes than its slot."""
    where = f"overlay {name}, {part} part"
    if first.entry != first.base:
        raise OverlayError(f"{where}: no entry {ENTRY} at its first byte")
    if first.relocations:
        raise OverlayError(f"{where}: relocations left {list(first.relocations)}")
    low, high = persistent.text
    calls = [
        symbol
        for symbol in first.undefined
        if symbol in persistent.symbols and low <= persistent.symbols[symbol][0] < high
    ]
    if calls:
        raise OverlayError(
            f"{where}: calls {calls[:4]} in the persistent kernel's text, which the "
            "runtime places elsewhere at run time; compile the call in instead"
        )
    copies = [
        symbol
        for symbol, (_, kind, _) in first.symbols.items()
        if kind == "OBJECT"
        and symbol in persistent.symbols
        and not (persistent.symbols[symbol][2] == "LOCAL" and symbol in RESETS + TABLES)
    ]
    if copies:
        raise OverlayError(
            f"{where}: its own copy of the runtime's state {copies[:4]}; the "
            "persistent kernel's is the one that counts"
        )
    if first.image != second.image:
        raise OverlayError(
            f"{where}: not position-independent: linked at {first.base:#x} and "
            f"{second.base:#x} its images differ"
        )
    if slot_bytes is not None and first.extent > slot_bytes:
        raise OverlayError(
            f"{where}: {first.extent} bytes (code, data and .bss) do not fit its "
            f"slot of {slot_bytes} bytes"
        )


def run(command, cwd=None):
    """Runs a build step; its failure is an OverlayError with the step's output."""
    done = subprocess.run(command, cwd=cwd, capture_output=True, text=True)
    if done.returncode:
        raise OverlayError(
            f"{Path(command[0]).name} failed: {shlex.join(command)}\n"
            f"{done.stdout}{done.stderr}"
        )
    return done.stdout


def run_into(out, command_of, cwd=None):
    """Runs the build step command_of(path) into a temporary name beside `out`, moved
    to `out` only when it returned 0: a stopped step never leaves a partial `out`."""
    temporary = out.with_name(f".{out.stem}-{os.getpid()}{out.suffix}")
    try:
        run(command_of(temporary), cwd=cwd)
        os.replace(temporary, out)
    finally:
        temporary.unlink(missing_ok=True)


def elf_symbols(recipe, elf, own=False):
    """{name: (value, kind, binding)} of an ELF's defined symbols; `own`: only those
    in its own sections (not the absolute ones another ELF's symbols gave it)."""
    found = {}
    for line in run([recipe.tool("readelf"), "-sW", str(elf)]).splitlines():
        words = line.split()
        defined = len(words) == 8 and words[0][:-1].isdigit() and words[6] != "UND"
        if defined and not (own and words[6] == "ABS"):
            found[words[7]] = (int(words[1], 16), words[3], words[4])
    return found


def persistent_facts(recipe):
    """The persistent kernel's .text range and symbols."""
    sections = run([recipe.tool("readelf"), "-SW", str(recipe.elf)])
    for line in sections.splitlines():
        words = line.replace("[ ", "[").split()
        if len(words) > 5 and words[1] == ".text":
            at, size = int(words[3], 16), int(words[5], 16)
            return Persistent((at, at + size), elf_symbols(recipe, recipe.elf))
    raise OverlayError(f"{recipe.elf}: no .text")


def linked_facts(recipe, elf, base, undefined):
    """The Linked facts of a part linked at `base`."""
    text = run([recipe.tool("readelf"), "-hlSW", str(elf)])
    relocations = tuple(re.findall(r"\]\s+(\.rela?\S*|\.dynamic)\s", text))
    symbols = elf_symbols(recipe, elf, own=True)
    loads = re.findall(
        r"LOAD\s+0x[0-9a-f]+ (0x[0-9a-f]+) 0x[0-9a-f]+ (0x[0-9a-f]+) (0x[0-9a-f]+)",
        text,
    )
    end = extent = base
    for vaddr, file_bytes, memory_bytes in loads:
        at = int(vaddr, 16)
        end = max(end, at + int(file_bytes, 16))
        extent = max(extent, at + int(memory_bytes, 16))
    extent = max(extent, symbols.get("__km_overlay_bss_end", (base,))[0])
    binary = elf.with_suffix(".bin")
    run([recipe.tool("objcopy"), "-O", "binary", str(elf), str(binary)])
    image = binary.read_bytes()[: end - base]
    image += bytes(-len(image) % ALIGN)
    entry = symbols.get(ENTRY, (None,))[0]
    return Linked(
        base, entry, relocations, symbols, tuple(undefined), extent - base, image
    )


def part_defines(overlay, kernel):
    """The defines of one part's build, and its compile arguments (None: the
    kernel's; a program's own overlay may carry the program's)."""
    function = FUNCTION
    if overlay.program:
        function = PROGRAM_FUNCTION
    elif overlay.message:
        function = MESSAGE_FUNCTION
    defines = {
        "KM_OVERLAY_PART": 1,
        "KM_OVERLAY_KERNEL": KERNEL_CLASSES[kernel],
        "KM_OVERLAY_FUNCTION": function,
        **({"KM_PROGRAM_PART": 1} if overlay.program else {}),
        **({"KM_MESSAGE_PART": 1, "KM_MESSAGE_PARTS": 1} if overlay.message else {}),
        **overlay.defines,
    }
    given = overlay.program or overlay.compile_args
    compile_args = overlay.compile_args.get(kernel, []) if given else None
    return defines, compile_args


def build_part(recipe, overlay, kernel, part, cache, slot_bytes=None, index=None):
    """Builds and checks one part: compiled with the runtime's commands, position-
    independent, linked at two bases; kept under `cache` by a hash of its preprocessed
    source, the recipe and the persistent ELF. Returns the first link's Linked;
    `index`: a file where its Linked and the files it includes are kept (built())."""
    stem = f"{re.sub(r'[^\w.-]', '_', overlay.name)}-{part}"
    scratch = Path(cache) / "sources"
    scratch.mkdir(parents=True, exist_ok=True)
    defines, compile_args = part_defines(overlay, kernel)
    recipe_key = hashlib.sha256(
        repr((recipe, defines, compile_args)).encode()
    ).hexdigest()[:16]
    wrapper = scratch / f"{stem}-{recipe_key}.cpp"
    source = Path(overlay.sources[kernel]).resolve()
    wrapper.write_text(WRAPPER.format(part=part, name=overlay.name, source=source))
    preprocessed = wrapper.with_suffix(".ii")
    run(
        recipe.compile_command(wrapper, preprocessed, defines, "-E", compile_args),
        cwd=scratch,
    )
    digest = hashlib.sha256(preprocessed.read_bytes() + recipe_key.encode())
    provided = recipe.provided()
    digest.update(recipe.elf.read_bytes() + (SCRIPT + provided).encode())
    work = Path(cache) / f"{stem}-{digest.hexdigest()[:16]}"
    work.mkdir(exist_ok=True)
    obj = work / "part.o"
    if not obj.is_file():
        run_into(
            obj,
            lambda path: recipe.compile_command(
                wrapper, path, defines, compile_args=compile_args
            ),
            cwd=work,
        )
    names = run([recipe.tool("gcc-nm"), "-u", str(obj)]).split()
    undefined = [name for name in names if name != "U"]
    links = []
    for base in (LINK_BASE, LINK_BASE + ALIGN):
        script, elf = work / f"part-{base:x}.ld", work / f"part-{base:x}.elf"
        script.write_text(SCRIPT.format(base=base, length=LINK_LENGTH) + provided)
        if not elf.is_file():
            run_into(
                elf, lambda path, ld=script: recipe.link_command(obj, ld, path), work
            )
        links.append(linked_facts(recipe, elf, base, undefined))
    check(overlay.name, part, *links, persistent_facts(recipe), slot_bytes)
    if index is not None:
        keep(index, links[0], preprocessed, work / f"part-{LINK_BASE:x}.elf")
    return links[0]


def included(preprocessed):
    """The files a preprocessed source was made of (its line markers), that exist."""
    folder = Path(preprocessed).parent  # where the preprocessor ran
    found = set(INCLUDED.findall(Path(preprocessed).read_text(errors="replace")))
    paths = {str((folder / path).resolve()) for path in found}
    return sorted(path for path in paths if Path(path).is_file())


def file_digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def built_key(recipe, overlay, kernel):
    """The key of a part in the cache of built parts: its source file, its defines and
    compile arguments, the recipe, the persistent kernel's ELF and the link script."""
    defines, compile_args = part_defines(overlay, kernel)
    digest = hashlib.sha256(
        repr(
            (
                str(Path(overlay.sources[kernel]).resolve()),
                recipe,
                defines,
                compile_args,
                SCRIPT + recipe.provided(),
                checks_key(),
            )
        ).encode()
    )
    digest.update(recipe.elf.read_bytes())
    return digest.hexdigest()[:32]


def checks_key():
    """The code that builds and checks a part (the builder, the part checks, the
    instruction check): a part kept in the cache is built and checked again once it
    changes, as it is not checked again when found."""
    return _env.code_key("overlay.py", "insn_check.py")


def keep(index, linked, preprocessed, elf):
    """Writes a built part's index: its Linked, its ELF, every file it includes with
    its digest."""
    record = {
        "linked": {
            "base": linked.base,
            "entry": linked.entry,
            "relocations": list(linked.relocations),
            "symbols": {k: list(v) for k, v in linked.symbols.items()},
            "undefined": list(linked.undefined),
            "extent": linked.extent,
            "image": linked.image.hex(),
        },
        "elf": str(elf),
        "files": {path: file_digest(path) for path in included(preprocessed)},
    }
    index.parent.mkdir(parents=True, exist_ok=True)
    temporary = index.with_name(f".{index.name}-{os.getpid()}")
    temporary.write_text(json.dumps(record))
    os.replace(temporary, index)


def built(index):
    """(Linked, ELF) of a part's index whose included files are unchanged, else None:
    nothing is compiled, linked or read with the toolchain."""
    if not index.is_file():
        return None
    record = json.loads(index.read_text())
    for path, digest in record["files"].items():
        if not Path(path).is_file() or file_digest(path) != digest:
            return None
    saved = record["linked"]
    linked = Linked(
        saved["base"],
        saved["entry"],
        tuple(saved["relocations"]),
        {k: tuple(v) for k, v in saved["symbols"].items()},
        tuple(saved["undefined"]),
        saved["extent"],
        bytes.fromhex(saved["image"]),
    )
    return linked, Path(record["elf"])


def build_part_cached(recipe, overlay, kernel, part, cache, slot_bytes=None):
    """build_part behind the cache of built parts (`cache`/built): a part whose key
    and included files are unchanged is not built again. (Linked, ELF, whether it was
    in the cache); a part larger than `slot_bytes` is refused either way."""
    index = Path(cache) / "built" / f"{built_key(recipe, overlay, kernel)}-{part}.json"
    found = built(index)
    if found is not None:
        linked, elf = found
        if slot_bytes is not None and linked.extent > slot_bytes:
            raise OverlayError(
                f"overlay {overlay.name}, {part} part: {linked.extent} bytes (code, "
                f"data and .bss) do not fit its slot of {slot_bytes} bytes"
            )
        return linked, elf, True
    linked = build_part(recipe, overlay, kernel, part, cache, slot_bytes, index)
    return linked, built(index)[1], False


@dataclass(frozen=True)
class Slots:
    """Slots per kernel: `count` (1 to 4) and `bytes` each (None: the largest part
    the kernel's overlays have), each an int for every kernel or a {kernel: value}."""

    count: object = None
    bytes: object = None
    service: object = None  # "own", "shared" or None: the load chooses

    def of(self, kernel, overlays):
        """(count, bytes or None) of `kernel` for `overlays` (with a part there)."""
        most = constants()["kOverlaySlotsMax"]
        count = self.count.get(kernel) if isinstance(self.count, dict) else self.count
        size = self.bytes.get(kernel) if isinstance(self.bytes, dict) else self.bytes
        if count is None:
            count = max(min(sum(kernel in o.sources for o in overlays), most), 1)
        if not 1 <= count <= most:
            raise ValueError(f"{kernel} slots: {count}, not in 1..{most}")
        if size is not None and (size <= 0 or size % ALIGN):
            raise ValueError(f"{kernel} slot bytes {size}: a multiple of {ALIGN}")
        return count, size

    def reserved(self, kernel):
        """Whether `kernel` has slots though no overlay has a part there: its `bytes`
        are named, for code added to the live run (run.addon)."""
        size = self.bytes.get(kernel) if isinstance(self.bytes, dict) else self.bytes
        return size is not None


@dataclass(frozen=True)
class Built:
    """A program's overlays built: images by (number, part), the programs' slots by
    part {part: (count, bytes)}, the service overlay's own reader slot (its bytes, 0:
    it shares the reader's), its part's bytes, why, every slot's bytes in L1 a core."""

    images: dict
    slots: dict
    service: int = 0
    service_part: int = 0
    why: str = ""

    @property
    def slot_bytes(self):
        return self.service + sum(count * size for count, size in self.slots.values())


def build(program, recipes, cache, log=lambda message: None):
    """Builds every part of the program's overlays against `recipes` ({target:
    Recipe} of its persistent kernels) and sizes the slots: a Built."""
    overlays = list(program.overlays.values())
    return build_overlays(overlays, program.overlay_slots, recipes, cache, log)


def build_overlays(overlays, declared_slots, recipes, cache, log=lambda message: None):
    """Builds every part of `overlays` against `recipes` ({target: Recipe} of the
    persistent kernels) and sizes the slots as `declared_slots` (Slots) says: a Built.
    """
    by_part = {TARGETS[target]: recipe for target, recipe in recipes.items()}
    island = any(
        "KM_PAGE_LINKS" in define
        for recipe in recipes.values()
        for define in recipe.defines
    )
    most, named = (
        (ISLAND_SERVICE_SLOT_MOST, "ISLAND_SERVICE_SLOT_MOST")
        if island
        else (SERVICE_SLOT_MOST, "SERVICE_SLOT_MOST")
    )
    declared, images, extents, service = {}, {}, {}, 0
    number = constants()["kOverlayService"]
    own = [overlay for overlay in overlays if overlay.number != number]
    for kernel in KERNELS:
        if declared_slots.reserved(kernel) or any(
            kernel in overlay.sources for overlay in own
        ):
            declared[kernel] = declared_slots.of(kernel, own)
    for overlay in overlays:
        for kernel, part in overlay.parts():
            # the service part sizes its own slot; a program's part meets its slots
            size = None if overlay.number == number else declared[kernel][1]
            builder = getattr(overlay, "build_part", None)  # a part of several units
            linked = (
                builder(by_part[part], kernel, part, cache, size)
                if builder is not None
                else build_part(by_part[part], overlay, kernel, part, cache, size)
            )
            images[overlay.number, part] = linked.image
            if overlay.number != number:
                extents.setdefault(part, []).append(linked.extent)
                log(f"overlay {overlay.name}: {part} part {len(linked.image)} B")
                continue
            service = -(-linked.extent // ALIGN) * ALIGN
            log(f"overlay {overlay.name}: {part} part {len(linked.image)} B, own slot")
            if linked.extent > most:  # the load's L1 table decides
                log(
                    f"the service overlay's {part} part takes {linked.extent:,} "
                    f"B, over {named} ({most:,} B): a class built with session= "
                    "reserved less than this load takes"
                )
    slots = {}
    for kernel, (count, size) in declared.items():
        for part in KERNEL_PARTS[kernel]:
            largest = -(-max(extents.get(part, [ALIGN])) // ALIGN) * ALIGN
            slots[part] = (count, size if size is not None else largest)
    return Built(images, slots, service, service)


def fitted(built, declared_slots, room, log=lambda message: None):
    """`built` with the slots of each kernel whose count was not declared lowered, one
    slot at a time from the largest, until they take at most `room` bytes (or each is
    at 1): what the L1 left allows."""
    slots = dict(built.slots)

    def free(part):
        kernel = next(k for k, parts in KERNEL_PARTS.items() if part in parts)
        count = declared_slots.count
        asked = count.get(kernel) if isinstance(count, dict) else count
        return asked is None and slots[part][0] > 1

    while built.service + sum(c * b for c, b in slots.values()) > room:
        lowered = [part for part in slots if free(part)]
        if not lowered:
            break
        part = max(lowered, key=lambda each: slots[each][1])
        slots[part] = (slots[part][0] - 1, slots[part][1])
        log(f"{part} slots lowered to {slots[part][0]}: the L1 left allows no more")
    return replace(built, slots=slots)


def shared(built):
    """`built` with the service overlay in the reader's slots (as large as its part
    at least, one at least) instead of a slot of its own."""
    slots = dict(built.slots)
    count, size = slots.get("reader", (1, 0))
    slots["reader"] = (count, max(size, built.service_part))
    return replace(built, slots=slots, service=0)


def held(built, alone):
    """The program parts `built`'s slots hold at once: its slots' count (a reader slot
    there only for the service, `alone`, holds none)."""
    return sum(count for count, _ in built.slots.values()) - alone


def choose(built, declared_slots, room, log=lambda message: None):
    """The service overlay's slot: its own (one more record) or the reader's shared,
    as `declared_slots.service` says, else as the L1 left (`room`) chooses; each
    fitted to the room, with why."""
    if not built.service_part:
        return fitted(built, declared_slots, room, log)
    alone = "reader" not in built.slots
    quiet = lambda message: None  # noqa: E731
    own = fitted(
        replace(built, service=built.service_part), declared_slots, room, quiet
    )
    common = fitted(shared(built), declared_slots, room, quiet)
    asked = declared_slots.service
    if asked not in (None, "own", "shared"):
        raise ValueError(f"service slot {asked!r}: 'own' or 'shared'")
    largest = max((size for _, size in built.slots.values()), default=0)
    if asked is not None:
        pick, why = asked, "as slots() asks"
    elif own.slot_bytes <= room and own.slots == built.slots:
        pick, why = "own", "the L1 left has the room"
    elif held(common, alone) != held(own, False):
        more = held(common, alone) > held(own, False)
        pick = "shared" if more else "own"
        why = f"it holds {max(held(common, alone), held(own, False))} program slots"
        why += f", not {min(held(common, alone), held(own, False))}"
    elif room - common.slot_bytes != room - own.slot_bytes:
        pick = "shared" if common.slot_bytes < own.slot_bytes else "own"
        why = f"it leaves {abs(common.slot_bytes - own.slot_bytes):,} B more of L1"
    else:
        pick = "own" if built.service_part > largest else "shared"
        why = "its part is the largest" if pick == "own" else "no slot is larger"
    chosen = (
        replace(built, service=built.service_part) if pick == "own" else shared(built)
    )
    made = fitted(chosen, declared_slots, room, log)  # its lowering logged
    log(f"service overlay: {'its own slot' if pick == 'own' else 'the reader slots'}"
        f" ({why})")  # fmt: skip
    return replace(made, why=why)


def dram_rows(built, reserve=0):
    """The DRAM image: every part's image in 8 pages (a copy in each bank, page i in
    bank i % 8), as uint32 rows; and {(number, part): (row of its first copy, bytes)}.
    `reserve`: bytes of room after them in each bank, for parts added later (zeros).
    """
    banks = constants()["kOverlayBanks"]
    width = max(len(image) for image in built.images.values())
    rooms = -(-reserve // width)
    rows = np.zeros((banks * (len(built.images) + rooms), width // 4), np.uint32)
    placed = {}
    for index, (key, image) in enumerate(sorted(built.images.items())):
        words = np.frombuffer(image, np.uint32)
        rows[banks * index : banks * (index + 1), : len(words)] = words
        placed[key] = (index, len(image))
    return rows, placed


def area_words(built, placed, image_address, image_page_bytes, slot_base):
    """The overlay area's words as the host writes them at load: the header (table
    entries, each part's first slot, slots and slot bytes) and the table."""
    c = constants()
    words = np.zeros(c["kOverlayAreaBytes"] // 4, np.uint32)
    numbers = [number for number, _ in built.images]
    words[c["kOverlayCount"]] = max(numbers) + 1 if numbers else 0
    words[c["kOverlayServiceSlot"] // 4] = built.service
    at = slot_base
    if built.service:  # its own slot first, its record one more than the reader's
        words[c["kOverlayServiceRecord"] // 4 + c["kOverlayAddress"]] = at
        at += built.service
    for index, part in enumerate(PARTS):
        count, size = built.slots.get(part, (0, 0))
        words[c["kOverlayBase"] + index] = at if count else 0
        words[c["kOverlaySlots"] + index] = count
        words[c["kOverlaySlotBytes"] + index] = size
        for slot in range(count):  # each record's slot address
            record = c["kOverlayRecords"] + 16 * (c["kOverlaySlotsMax"] * index + slot)
            words[record // 4 + c["kOverlayAddress"]] = at
            at += size
    for (number, part), (row, size) in placed.items():
        entry = (
            c["kOverlayTable"] + 8 * (c["kOverlayParts"] * number + PARTS.index(part))
        ) // 4
        words[entry] = image_address + row * image_page_bytes
        words[entry + 1] = size
    return words


def budget(free, rows):
    """The L1 budget table of a core as text, and whether `rows` ([(name, bytes)])
    fit the `free` bytes the runtime leaves for buffers."""
    used = sum(size for _, size in rows)
    lines = [f"  {name:<40} {size:>9,} B" for name, size in rows]
    lines.append(f"  {'total':<40} {used:>9,} B of {free:,} B")
    return "\n".join(lines), used <= free
