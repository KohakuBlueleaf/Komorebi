"""Several programs merged into ONE program (`km.merge(a, b, ...)`): one program field,
one handler numbering, one L1 layout. Each source in the runtime's form keeps its text
and its own handler numbers; the merged program's part maps a command to its source.
"""

import dataclasses
import hashlib
import importlib
import re
from pathlib import Path

from komorebi import native, overlay, programs
from komorebi import overlay as overlay_module
from komorebi.errors import L1LayoutError, ProgramError
from komorebi.program import Handler, Program

USER_MAX = 239  # KM_HANDLER_USER_MAX: a program's handlers are numbered 1 to 239
SOURCE_FUNCTION = "km_merged_source_{index}"  # source `index`'s entry in the part
PROGRAM_FUNCTION = "km_merged_program_{index}"  # its km_program, renamed by a define
# Slots a kernel when a source is an overlay: the merged part, one shared slot for the
# sources placed as overlays, and on the reader the service overlay's.
OVERLAY_SLOTS = {"reader": 3, "writer": 2, "compute": 2}
UNIT_NAME = re.compile(r"\.unit-\d+$")  # what own_unit adds to a unit's names
CODE = "TtW"  # nm's kinds of a function a unit defines: renamed, the unit's own
DATA = "BDRGS"  # a global datum a header defines in each unit: weak, one copy
# How a source's unit becomes code of its own (own_unit); part of a part's cache key.
OWN_UNIT = "nolto-rel, a section a function, functions renamed, data weak, gc-sections"
DISPATCHER = """\
// Generated by km.merge: the part of program {name} on each kernel. A command's
// handler is mapped to its source and the source's own number.
#include <stdint.h>

#include "komorebi/device/km_overlay.hpp"
#include "komorebi/device/km_program.hpp"

{declarations}
namespace {{

    // The command with the source's own handler number in place of the merged one.
    inline km_command_t km_merged_own(const km_command_t& command, uint32_t own) {{
        km_command_t mapped = command;
        mapped.hdr = (command.hdr & ~0xFFu) | own;
        return mapped;
    }}

    // A source placed as an overlay: loaded into the shared slot unless held, called.
    inline uint32_t km_merged_overlay(
        KM_OVERLAY_KERNEL& kernel, uint32_t number, const km_command_t& command
    ) {{
        km::Overlay<KM_OVERLAY_KERNEL> part(kernel, number);
        if (!part.load()) {{
            return 0;  // the give-up path
        }}
        return part.call(command);
    }}

    // 1 completes the command (the writer's); a number no source has does nothing.
    uint32_t km_merged_call(KM_OVERLAY_KERNEL& kernel, const km_command_t& command) {{
        switch (km::handler(command)) {{
{cases}
        }}
        return 1;
    }}

}}  // namespace

namespace km {{

    // A chain's record (km_chain.hpp under KM_MERGED_SOURCE): to its source.
    bool merged_record(KM_OVERLAY_KERNEL& kernel, const km_command_t& record) {{
        return km_merged_call(kernel, record) != 0;
    }}

}}  // namespace km

bool km_program(KM_OVERLAY_KERNEL& kernel, const km_command_t& command) {{
    return km_merged_call(kernel, command) != 0;
}}
"""
SOURCE = """\
// Generated by km.merge: source {index} ({source}) of program {name}, as written; the
// part calls it with the command's handler the source's own.
#include "komorebi/device/km_overlay_part.hpp"
#include "{path}"

namespace {{

    template <typename Kernel>
    inline uint32_t km_merged_result(
        void (*function)(Kernel&, const km_command_t&),
        Kernel& kernel,
        const km_command_t& command
    ) {{
        function(kernel, command);
        return 1;
    }}

    template <typename Kernel>
    inline uint32_t km_merged_result(
        bool (*function)(Kernel&, const km_command_t&),
        Kernel& kernel,
        const km_command_t& command
    ) {{
        return function(kernel, command) ? 1u : 0u;
    }}

}}  // namespace

extern "C" uint32_t {function}(
    KM_OVERLAY_KERNEL& kernel, const km_command_t& command
) {{
#if defined(TRISC_MATH)
    ckernel::math::_invalidate_src_zero_flag_state_();  // this source's copy: unknown
#endif
    return km_merged_result<KM_OVERLAY_KERNEL>(km_program, kernel, command);
}}
"""


def merge(
    *sources, name=None, overlay=(), resident=(), session=None, l1=None, log=print
):
    """ONE program from `sources`: programs in the runtime's form (Merged), or made
    class programs (komorebi.dsl.merged, one program in the kernel form). A program
    in the kernel form, and a class with a hand program, are refused with the way."""
    classes = [hasattr(source, "make_given") for source in sources]
    if any(classes) and all(classes):
        made = importlib.import_module("komorebi.dsl.merged")  # it imports the DSL
        return made.merge_made(sources, name, overlay, resident, session, l1, log)
    if any(classes):
        raise ProgramError(
            f"{', '.join(getattr(s, 'name', repr(s)) for s in sources)}: a class with "
            "a hand program: a class is built in the kernel form (its kernel_main and "
            "loop), a hand program merges in the runtime's form; merge classes with "
            "classes, hand programs with hand programs (docs/reference/host.md)"
        )
    return Merged(sources, name, overlay, resident, session, l1, log)


class Merged(Program):
    """Programs merged into one: handlers numbered over the sources (the first keeps
    its numbers, each next one follows), buffers in one layout, each kernel's part the
    sources' code with a table from the merged number to the source's own."""

    def __init__(
        self,
        sources,
        name=None,
        overlay=(),
        resident=(),
        session=None,
        l1=None,
        log=print,
    ):
        sources = tuple(sources)
        _check_sources(sources)
        name = name or "+".join(source.name for source in sources)
        numbers, handlers, shared = _numbering(name, sources)
        free = session.l1()[1] if session is not None else l1
        owner = _threads_owner(sources)
        first = sources[0]
        for attribute, what in (("compute", "compute options"), ("opt", "opt levels")):
            programs._same(sources, attribute, what)
        programs._same_nocs(sources, "programs merged into one")
        common = {
            key: value
            for key, value in first.defines.items()
            if all(source.defines.get(key) == value for source in sources)
        }
        with_args = [source for source in sources if source.args is not None]
        if len(with_args) > 1:
            raise ProgramError(
                f"{name}: per-core args of {', '.join(s.name for s in with_args)}; "
                "one source of a merged program may take them"
            )
        self.merged_sources = sources
        self.numbers = numbers  # merged number -> (source index, its own number)
        self.shared_names = shared  # a name two sources have -> their indices
        self.log = log
        self.code_overlays = set()  # sources placed as overlays
        self.pinned = set()  # sources a marker keeps resident
        self.part_bytes = {}  # source index -> {part: bytes}, built as an overlay
        self._built = None
        self._recipes = {}
        Program.__init__(
            self,
            name,
            kernels=None,
            buffers=_joint_buffers(name, sources, free),
            args=with_args[0].args if with_args else None,
            compute=dict(first.compute),
            defines=common,
            depth=max(source.depth for source in sources),
            handlers=handlers,
            threads=dict(owner.threads) if owner else {},
            shared=dict(owner.shared) if owner else {},
            opt=dict(first.opt),
            noc=dict(first.noc),
        )
        self.x280_ports = owner.x280_ports if owner else None
        self._markers(overlay, resident)
        if self.code_overlays:
            self.overlay_slots = overlay_module.Slots(count=dict(OVERLAY_SLOTS))
        self.kernels = self._dispatcher()
        for line in self.report():
            log(line)

    # The merged program's handlers ------------------------------------------------

    def handler(self, handler, name=None):
        """The merged Handler of `handler`: a name one source alone has, a number, a
        source's own Handler (`a.handler("gate")`), or (source, name) when two
        sources share the name."""
        if name is not None:
            return self.handler(self.merged_sources[self._index(handler)].handler(name))
        if isinstance(handler, Handler) and handler.program is not self:
            index = self._index(handler.program)
            for number, (source, own) in self.numbers.items():
                if source == index and own == int(handler):
                    return Handler(number, self)
            raise ValueError(f"{handler!r}: no such handler of {handler.program.name}")
        if isinstance(handler, str) and handler in self.shared_names:
            owners = [self.merged_sources[i].name for i in self.shared_names[handler]]
            raise ValueError(
                f"{self.name}: handler {handler!r} is in {' and '.join(owners)}; name "
                f"its source: merged.handler({owners[0]}, {handler!r})"
            )
        return Program.handler(self, handler)

    def _index(self, source):
        for index, given in enumerate(self.merged_sources):
            if given is source:
                return index
        raise ValueError(
            f"{getattr(source, 'name', source)!r}: not a source of {self.name}"
        )

    def report(self):
        """The build's report: each source's handlers and their merged numbers."""
        lines = [f"merged program {self.name}: handler numbers"]
        for number, (index, own) in sorted(self.numbers.items()):
            source = self.merged_sources[index]
            names = [n for n, value in source.handlers.items() if value == own]
            lines.append(
                f"  {number:>3}: {source.name}.{names[0] if names else own} "
                f"({source.name}'s {own})"
            )
        return lines

    # Where the code lives ----------------------------------------------------------

    def _markers(self, overlay_marked, resident_marked):
        """The markers: sources placed as overlays, sources kept resident."""
        for marked, into in (
            (overlay_marked, self.code_overlays),
            (resident_marked, self.pinned),
        ):
            for item in marked:
                if isinstance(item, str | Handler):
                    owner = (
                        item.program.name
                        if isinstance(item, Handler)
                        else ", ".join(
                            s.name for s in self.merged_sources if item in s.handlers
                        )
                        or "none of its sources"
                    )
                    raise ProgramError(
                        f"{self.name}: {item!r} names a handler; a hand source's "
                        f"handlers are one switch the build cannot cut: name its "
                        f"source ({owner})"
                    )
                into.add(self._index(item))
        both = self.code_overlays & self.pinned
        if both:
            raise ProgramError(
                f"{self.name}: "
                f"{', '.join(self.merged_sources[i].name for i in sorted(both))} "
                "marked both overlay and resident"
            )

    def _dispatcher(self):
        """{kernel: path} of the generated part source for the current placement."""
        declarations, cases = [], []
        for index, source in enumerate(self.merged_sources):
            if index not in self.code_overlays:
                function = SOURCE_FUNCTION.format(index=index)
                declarations.append(
                    f'extern "C" uint32_t {function}(KM_OVERLAY_KERNEL&, '
                    "const km_command_t&);"
                    f"  // {source.name}"
                )
        for number, (index, own) in sorted(self.numbers.items()):
            # a source's own number equal to the merged one: the command as it came
            mapped = "command" if own == number else f"km_merged_own(command, {own}u)"
            if index in self.code_overlays:
                part = self.overlay_number(index)
                call = f"km_merged_overlay(kernel, {part}u, {mapped})"
            else:
                call = f"{SOURCE_FUNCTION.format(index=index)}(kernel, {mapped})"
            source = self.merged_sources[index].name
            cases.append(f"            case {number}u:  // {source}'s {own}")
            cases.append(f"                return {call};")
        text = DISPATCHER.format(
            name=self.name,
            declarations="\n".join(declarations) + ("\n" if declarations else ""),
            cases="\n".join(cases),
        )
        digest = hashlib.sha256(text.encode()).hexdigest()[:12]
        slug = re.sub(r"[^\w.-]", "_", self.name)
        path = native.cache_directory() / "merged" / f"{slug}-{digest}" / "program.cpp"
        if not path.is_file():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        return {kernel: path for kernel in overlay.KERNELS}

    def overlay_number(self, index):
        """The overlay number of source `index` placed as an overlay: 1 on."""
        return 1 + sorted(self.code_overlays).index(index)

    def place_overlay(self, index):
        """Source `index` becomes an overlay: its part loaded on demand into a slot
        the sources placed as overlays share."""
        self.code_overlays.add(index)
        self.kernels = self._dispatcher()
        self.overlay_slots = overlay.Slots(count=dict(OVERLAY_SLOTS))

    def part_overlays(self, switch=False, alone=True):
        """The overlays a load builds for this program: the merged part (its program
        field's number) and each source placed as an overlay (numbers from 1)."""
        if self.code_overlays and (switch or not alone):
            raise ProgramError(
                f"{self.name}: a source placed as an overlay takes the run's slots and "
                "overlay numbers; a merged program with one is loaded alone"
            )
        made = programs.program_overlay(self, switch)
        part = MergedOverlay(
            made.name,
            made.number,
            made.sources,
            made.defines,
            program=True,
            compile_args={kernel: [] for kernel in overlay.KERNELS},
            merged=self,
        )
        return [part, *(self._source_overlay(i) for i in sorted(self.code_overlays))]

    def _source_overlay(self, index, number=None):
        """Source `index` as an ordinary program part (`number`: its overlay's)."""
        source = self.merged_sources[index]
        return overlay.Overlay(
            f"{self.name}.{source.name}",
            number or self.overlay_number(index),
            {kernel: Path(path) for kernel, path in source.sources().items()},
            dict(source.defines),
            program=True,
            compile_args={k: source.kernel_compile_args(k) for k in overlay.KERNELS},
        )

    def spill(self, log):
        """After a load's L1 table did not fit: the largest resident source no marker
        keeps becomes an overlay (True), or there is none (False)."""
        free = [
            index
            for index in range(len(self.merged_sources))
            if index not in self.code_overlays | self.pinned
        ]
        if not free:
            return False
        sizes = {index: sum(self.source_bytes(index).values()) for index in free}
        index = max(free, key=lambda i: (sizes[i], -i))
        log(
            f"{self.name}: L1 over: source {self.merged_sources[index].name} "
            f"({sizes[index]:,} B of parts) becomes an overlay"
        )
        self.place_overlay(index)
        return True

    def source_bytes(self, index):
        """{part: bytes} of source `index` built as a part of its own."""
        if index not in self.part_bytes:
            made = self._source_overlay(index, 1 + index)  # the number sizes nothing
            cache = native.cache_directory() / "overlays"
            self.part_bytes[index] = {
                part: overlay.build_part(
                    self._recipes[part], made, kernel, part, cache
                ).extent
                for kernel, part in made.parts()
            }
        return self.part_bytes[index]

    @property
    def overlays_built(self):
        return self._built

    @overlays_built.setter
    def overlays_built(self, built):
        """The load's build of the parts: kept, and where the code lives logged."""
        self._built = built
        if built is not None and getattr(self, "numbers", None):
            for line in self.code_table(built):
                self.log(line)

    def code_table(self, built):
        """Where each source's handlers' code lives, once the session built it."""
        lines = ["where the handlers' code lives:"]
        own = self.program_field_number()
        for index, source in enumerate(self.merged_sources):
            numbers = [n for n, (i, _) in sorted(self.numbers.items()) if i == index]
            handlers = ", ".join(str(n) for n in numbers)
            if index not in self.code_overlays:
                sizes = self.source_bytes(index)
                where = f"resident, in the part (overlay {own}); alone it is "
                where += ", ".join(f"{p} {b:,} B" for p, b in sizes.items())
                lines.append(f"  {source.name} (handlers {handlers}): {where}")
                continue
            number = self.overlay_number(index)
            sizes = ", ".join(
                f"{part} {len(built.images[number, part]):,} B"
                for part in overlay.PARTS
                if (number, part) in built.images
            )
            lines.append(
                f"  {source.name} (handlers {handlers}): overlay {number}: {sizes}"
            )
        slots = ", ".join(
            f"{part} {count} x {size:,} B"
            for part, (count, size) in built.slots.items()
        )
        lines.append(f"  slots: {slots}")
        return lines

    def program_field_number(self):
        """The overlay number of the merged part: its program field's."""
        return overlay.constants()["kOverlayService"] - 1 - self.program_field


class MergedOverlay(overlay.Overlay):
    """The merged program's part: built from the generated part source and each
    resident source as its own unit, linked into one part."""

    merged: object = None

    def __init__(self, *args, merged=None, **kwargs):
        super().__init__(*args, **kwargs)
        object.__setattr__(self, "merged", merged)

    def build_part(self, recipe, kernel, part, cache, slot_bytes=None):
        """Builds and checks one part: overlay.build_part's steps over several
        units (the part source with the entry, each resident source)."""
        merged = self.merged
        merged._recipes[part] = recipe
        units = [
            (
                overlay.WRAPPER.format(
                    part=part, name=self.name, source=self.sources[kernel]
                ),
                {
                    "KM_OVERLAY_FUNCTION": overlay.PROGRAM_FUNCTION,
                    "KM_PROGRAM_PART": 1,
                    **self.defines,
                },
                [],
                None,
            )
        ]
        for index, source in enumerate(merged.merged_sources):
            if index in merged.code_overlays:
                continue
            path = Path(source.sources()[kernel]).resolve()
            text = SOURCE.format(
                index=index,
                source=source.name,
                name=merged.name,
                path=path,
                function=SOURCE_FUNCTION.format(index=index),
            )
            defines = {
                "KM_MERGED_SOURCE": 1,
                "km_program": PROGRAM_FUNCTION.format(index=index),
                **source.defines,
            }
            function = SOURCE_FUNCTION.format(index=index)
            units.append((text, defines, source.kernel_compile_args(kernel), function))
        return build_units(recipe, self.name, kernel, part, units, cache, slot_bytes)


def build_units(recipe, name, kernel, part, units, cache, slot_bytes=None):
    """overlay.build_part for a part of several units [(text, defines, compile
    args, the entry a source's unit keeps or None)]: each compiled with the runtime's
    commands, linked at two bases and checked; kept by a hash of every unit."""
    stem = f"{re.sub(r'[^\w.-]', '_', name)}-{part}"
    scratch = Path(cache) / "sources"
    scratch.mkdir(parents=True, exist_ok=True)
    base_defines = {
        "KM_OVERLAY_PART": 1,
        "KM_OVERLAY_KERNEL": overlay.KERNEL_CLASSES[kernel],
    }
    digest = hashlib.sha256(repr(recipe).encode())
    made = []
    for number, (text, defines, compile_args, keep) in enumerate(units):
        defines = {**base_defines, **defines}
        key = hashlib.sha256(repr((recipe, defines, compile_args)).encode()).hexdigest()
        wrapper = scratch / f"{stem}-{number}-{key[:16]}.cpp"
        wrapper.write_text(text)
        preprocessed = wrapper.with_suffix(".ii")
        overlay.run(
            recipe.compile_command(wrapper, preprocessed, defines, "-E", compile_args),
            cwd=scratch,
        )
        digest.update(preprocessed.read_bytes() + key.encode())
        made.append((wrapper, defines, compile_args, keep))
    provided = recipe.provided()
    digest.update(recipe.elf.read_bytes() + (overlay.SCRIPT + provided).encode())
    digest.update(OWN_UNIT.encode())
    work = Path(cache) / f"{stem}-merged-{digest.hexdigest()[:16]}"
    work.mkdir(exist_ok=True)
    objects = []
    for number, (wrapper, defines, compile_args, keep) in enumerate(made):
        obj = work / f"unit-{number}.o"
        if not obj.is_file():
            overlay.run_into(
                obj,
                lambda path, w=wrapper, d=defines, c=compile_args: (
                    recipe.compile_command(w, path, d, compile_args=c)
                ),
                cwd=work,
            )
        if keep is not None:  # its own code, every name but its entry its own
            obj = own_unit(recipe, obj, keep)
        objects.append(obj)
    undefined = set()
    for obj in objects:
        names = overlay.run([recipe.tool("gcc-nm"), "-u", str(obj)]).split()
        undefined |= {n for n in names if n != "U"}
    links = []
    for base in (overlay.LINK_BASE, overlay.LINK_BASE + overlay.ALIGN):
        script, elf = work / f"part-{base:x}.ld", work / f"part-{base:x}.elf"
        script.write_text(
            overlay.SCRIPT.format(base=base, length=overlay.LINK_LENGTH) + provided
        )
        if not elf.is_file():
            overlay.run_into(
                elf,
                lambda path, ld=script: link_command(recipe, objects, ld, path),
                work,
            )
        linked = overlay.linked_facts(recipe, elf, base, sorted(undefined))
        symbols = {UNIT_NAME.sub("", n): fact for n, fact in linked.symbols.items()}
        links.append(dataclasses.replace(linked, symbols=symbols))  # as written
    overlay.check(name, part, *links, overlay.persistent_facts(recipe), slot_bytes)
    return links[0]


def own_unit(recipe, obj, keep):
    """A source's unit as code of its own: optimised alone (its link-time step into a
    relocatable object, a section a function), each function but `keep` renamed for
    the unit, its global data weak: one copy of data a part, as in one unit."""
    code, out = obj.with_name(f"{obj.stem}-code.o"), obj.with_name(f"{obj.stem}-own.o")
    if not out.is_file():
        flags = [w for w in recipe.lflags if not w.startswith(overlay.DROPPED_LINK)]
        overlay.run_into(
            code,
            lambda path: [
                *recipe.compiler,
                f"-{recipe.link_opt}",
                *flags,
                "-nostdlib",
                "-r",
                "-flinker-output=nolto-rel",
                "-ffunction-sections",
                "-fdata-sections",
                str(obj),
                "-o",
                str(path),
            ],
        )
        names = overlay.run([recipe.tool("nm"), "--defined-only", str(code)])
        defined = [line.split() for line in names.splitlines()]
        defined = [words[1:] for words in defined if len(words) == 3]
        renamed = obj.with_name(f"{obj.stem}-names.txt")
        renamed.write_text(
            "".join(
                f"{name} {name}.{obj.stem}\n"
                for kind, name in defined
                if kind in CODE and name != keep
            )
        )
        shared = [f"--weaken-symbol={name}" for kind, name in defined if kind in DATA]
        overlay.run_into(
            out,
            lambda path: [
                recipe.tool("objcopy"),
                f"--redefine-syms={renamed}",
                *shared,
                str(code),
                str(path),
            ],
        )
    return out


def link_command(recipe, objects, script, out):
    """Recipe.link_command over several objects, unreached sections dropped."""
    return [
        *recipe.compiler,
        f"-{recipe.link_opt}",
        *(w for w in recipe.lflags if not w.startswith(overlay.DROPPED_LINK)),
        "-Wl,--gc-sections",
        f"-T{script}",
        f"-Wl,--just-symbols={recipe.elf}",
        *(str(obj) for obj in objects),
        "-o",
        str(out),
    ]


def lifted(handler, loaded):
    """A source's own Handler as the merged program's, when a program of `loaded`
    merged its program; else `handler` as given."""
    for program in loaded:
        sources = getattr(program, "merged_sources", ())
        if any(source is handler.program for source in sources):
            return program.handler(handler)
    return handler


def _check_sources(sources):
    """Refuses what merge does not take, each with its reason."""
    if len(sources) < 2:
        raise ValueError("merge takes two or more programs")
    if len({id(source) for source in sources}) != len(sources):
        raise ValueError("a program is given twice")
    for source in sources:
        if not isinstance(source, Program):
            raise TypeError(f"merge takes Programs: {source!r}")
        if isinstance(source, Merged):
            raise ProgramError(
                f"{source.name}: a merged program; merge its sources with the others"
            )
        if getattr(type(source), "built_handlers", None) is not None:
            raise ProgramError(
                f"{source.name}: a class is in the kernel form; programs in the "
                "runtime's form (km_program) are merged"
            )
        if source.form() != "program":
            raise ProgramError(
                f"{source.name}: its sources define kernel_main, so they own the "
                "kernel and its loop; a program merges in the runtime's form, each "
                "source defining km_program (docs/reference/host.md)"
            )
        if source.overlays:
            raise ProgramError(
                f"{source.name}: it has overlays of its own, whose numbers a merged "
                "program's sources placed as overlays take; not merged"
            )
        programs.check(source, 1)


def _numbering(name, sources):
    """({merged: (source index, own)}, {name: merged}, {shared name: [indices]}):
    the first source keeps its numbers, each next one takes the next numbers."""
    numbers, handlers, top = {}, {}, 0
    owners = {}
    for index, source in enumerate(sources):
        own = sorted(set(source.handlers.values()))
        if index == 0:
            mapped = {number: number for number in own}
        else:
            mapped = {number: top + 1 + place for place, number in enumerate(own)}
        for number in own:
            numbers[mapped[number]] = (index, number)
        top = max([top, *mapped.values()])
        for handler, number in source.handlers.items():
            owners.setdefault(handler, []).append((index, mapped[number]))
    if top > USER_MAX:
        raise ProgramError(
            f"{name}: {len(numbers)} handlers numbered up to {top}; a program numbers "
            f"its handlers 1 to {USER_MAX}"
        )
    shared = {}
    for handler, found in owners.items():
        if len(found) == 1:
            handlers[handler] = found[0][1]
            continue
        shared[handler] = [index for index, _ in found]
        for index, number in found:
            handlers[f"{sources[index].name}.{handler}"] = number
    return numbers, handlers, shared


def _threads_owner(sources):
    """The source whose X280 threads and ports the merged program has: the first;
    another source with them is refused (their commands name its own numbers)."""
    owners = [s for s in sources if s.threads or s.x280_ports is not None]
    if not owners:
        return None
    if len(owners) > 1:
        raise ProgramError(
            f"{', '.join(s.name for s in owners)}: X280 threads and ports belong to "
            "one program of a run; declare them in one"
        )
    if owners[0] is not sources[0]:
        raise ProgramError(
            f"{owners[0].name}: its X280 threads name its own handler numbers, which "
            "only the first source keeps; merge it first"
        )
    return owners[0]


def _joint_buffers(name, sources, free):
    """The list load's rule over the sources: an index declared identically is one
    buffer; declared two ways, L1LayoutError naming both with the L1 table."""
    by_index, owner = {}, {}
    for source in sources:
        for buffer in source.buffers:
            seen = by_index.get(buffer.index)
            if seen is None:
                by_index[buffer.index], owner[buffer.index] = buffer, source.name
            elif seen != buffer:
                table, _ = overlay.budget(free or 0, programs.budget_rows(sources))
                if free is None:
                    table = table.rsplit(" of ", 1)[0]
                raise L1LayoutError(
                    f"{name}: buffer {buffer.index} is declared by "
                    f"{owner[buffer.index]} as {programs._text(seen)} and by "
                    f"{source.name} as {programs._text(buffer)}",
                    table,
                )
    return [by_index[index] for index in sorted(by_index)]
