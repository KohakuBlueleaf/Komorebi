/* Trap guard: an exception ends in kmd_trapped and main returns; core 0's software
 * interrupt re-enters its loop (kmd_resumed); others go to the runtime's handler. */
#pragma once

__asm__(
    ".text\n"
    ".global main\n"
    ".type main, @function\n"
    "main:\n"
    "    addi sp, sp, -128\n"
    /* main's words 112 and 120: run()'s sp and the state once core 0's loop runs */
    "    sd zero, 112(sp)\n"
    "    sd zero, 120(sp)\n"
    "    sd ra, 0(sp)\n"
    "    sd s0, 8(sp)\n"
    "    sd s1, 16(sp)\n"
    "    sd s2, 24(sp)\n"
    "    sd s3, 32(sp)\n"
    "    sd s4, 40(sp)\n"
    "    sd s5, 48(sp)\n"
    "    sd s6, 56(sp)\n"
    "    sd s7, 64(sp)\n"
    "    sd s8, 72(sp)\n"
    "    sd s9, 80(sp)\n"
    "    sd s10, 88(sp)\n"
    "    sd s11, 96(sp)\n"
    "    csrr t0, mtvec\n"
    "    sd t0, 104(sp)\n"
    "    csrw mscratch, sp\n"
    "    la t0, kmd_trap\n"
    "    csrw mtvec, t0\n"
    "    call kmd_main\n"
    "kmd_trap_return:\n"
    "    ld t0, 104(sp)\n"
    "    csrw mtvec, t0\n"
    "    ld ra, 0(sp)\n"
    "    ld s0, 8(sp)\n"
    "    ld s1, 16(sp)\n"
    "    ld s2, 24(sp)\n"
    "    ld s3, 32(sp)\n"
    "    ld s4, 40(sp)\n"
    "    ld s5, 48(sp)\n"
    "    ld s6, 56(sp)\n"
    "    ld s7, 64(sp)\n"
    "    ld s8, 72(sp)\n"
    "    ld s9, 80(sp)\n"
    "    ld s10, 88(sp)\n"
    "    ld s11, 96(sp)\n"
    "    addi sp, sp, 128\n"
    "    ret\n"
    ".size main, . - main\n"
    /* mtvec's two low bits are its mode: 4-byte aligned is direct. */
    ".balign 4\n"
    "kmd_trap:\n"
    "    csrr t0, mcause\n"
    "    bltz t0, 2f\n"
    "    csrr sp, mscratch\n"
    "    ld t0, 104(sp)\n"
    "    csrw mtvec, t0\n"
    "    csrr a0, mhartid\n"
    "    csrr a1, mcause\n"
    "    csrr a2, mepc\n"
    "    csrr a3, mtval\n"
    "    call kmd_trapped\n"
    "    la t0, kmd_trap_return\n"
    "    csrw mepc, t0\n"
    "    li a0, 0\n"
    "    mret\n"
    /* Machine software interrupt (cause 3) with a saved frame: never returns to mepc.
     */
    "2:  li t1, 0x8000000000000003\n"
    "    bne t0, t1, 1f\n"
    "    csrr t0, mscratch\n"
    "    ld t1, 112(t0)\n"
    "    beqz t1, 1f\n"
    "    mv sp, t1\n"
    "    ld a0, 120(t0)\n"
    "    csrr a1, mepc\n"
    "    call kmd_resumed\n"
    "    csrr sp, mscratch\n"
    "    li a0, 0\n"
    "    j kmd_trap_return\n"
    "1:  j _trap_handler\n"
);
