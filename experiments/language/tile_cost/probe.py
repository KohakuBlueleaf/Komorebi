"""Tile-cost probes: what each CPU of one compute core spends on a tile (README.md).
`probe.py build`: a mock device builds the kernels of the chosen sections;
`probe.py card`: runs them on one core and prints per-CPU spans and the tile's counters
of every repeat."""

