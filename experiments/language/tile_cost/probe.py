HERE = Path(__file__).resolve().parent
KERNELS = HERE / "kernels"
GENERATED = HERE / "generated"
JIT_CACHE = HERE.parents[2] / ".logs" / "jit-cost" / "mock"
DESCRIPTOR = (
    "tt_metal/third_party/umd/tests/cluster_descriptor_examples/blackhole_P150.yaml"
)
COUNTERS_HEADER = "tt_metal/tt-llk/tools/include/perf_counters/blackhole.h"
BANKS = ("instrn_counters", "fpu_counters", "unpack_counters", "pack_counters")
CB_A, CB_B, CB_ALT, CB_OUT, CB_OUT_ALT, CB_INFO = 0, 1, 2, 16, 17, 24
NONCE, ERROR, REPEATS, TILES, THROTTLE, DBG_DISABLE = 0, 1, 2, 3, 4, 5
FAIL = 12  # three words: a barrier a CPU gave up at, or 0
SYNC, SYNCS, REP, REP_STRIDE = 16, 16, 64, 112
READ_TIME, REFS, COUNTERS = 6, 8, 12
TILE_WORDS = 1024
FORMATS = {  # name: (dtype, bytes a tile)
    "bf16": ("bfloat16", 2048),
    "bfp8_b": ("bfp8_b", 1088),
    "bfp4_b": ("bfp4_b", 576),
    "fp32": ("float32", 4096),
}


def log(message):
    print(f"[{time.strftime('%H:%M:%S')}] {message}", flush=True)


# ---------------------------------------------------------------- the counters' table


def counter_tables(tree):
    """[(name, select)] of the four banks, parsed from tt-llk's Blackhole table (the
    kernel's table is generated from the same text)."""
    text = (tree / COUNTERS_HEADER).read_text()
    tables = []
    for bank in BANKS:
        body = re.search(rf"(?<![a-z_]){bank} = \{{(.*?)\}}\}};", text, re.S).group(1)
        entries = re.findall(r"\{PerfCounterType::(\w+), (\d+)\}", body)
        tables.append([(name, int(sel)) for name, sel in entries])
    return tables


def write_counters_header(tables):
    GENERATED.mkdir(exist_ok=True)
    widest = max(len(t) for t in tables)
    rows = [
        "    {"
        + ", ".join(str(sel) for _, sel in t + [("", 0)] * (widest - len(t)))
        + "}"
        for t in tables
    ]
    text = (
        "// Generated by probe.py from tt-llk's Blackhole counter tables.\n"
        "#pragma once\n#include <stdint.h>\nnamespace counters {\n"
        "    constexpr uint32_t kSizes[4] = "
        f"{{{', '.join(str(len(t)) for t in tables)}}};\n"
        f"    constexpr uint16_t kSelects[4][{widest}] = {{\n"
        + ",\n".join(rows)
        + "\n    };\n}\n"
    )
    (GENERATED / "counters_table.hpp").write_text(text)


# ---------------------------------------------------------------- vector bodies


def stream(name, inputs, fn):
    """The IR of y = fn(a, ..) over a stream of fp32 tiles."""
    params = [TensorParam(n, False, F32) for n in "abc"[:inputs]]
    y = TensorParam("y", True, F32)
    ir = KernelIR(name, [*params, y], [], {})
    with trace.Tracer(ir):
        proxies = [trace.TensorProxy(p) for p in params]
        ys = trace.TensorProxy(y)
        for t in trace.grid(trace.num_tiles(proxies[0])):
            loads = [trace.load(p.tiles[t]) for p in proxies]
            trace.store(ys.tiles[t], fn(*loads))
    return ir


def row_ir(name, fn):
    """y = fn(row) over rows of tiles."""
    x, y = TensorParam("x", False, F32), TensorParam("y", True, F32)
    ir = KernelIR(name, [x, y], [], {})
    with trace.Tracer(ir):
        xs, ys = trace.TensorProxy(x), trace.TensorProxy(y)
        for t in trace.grid(trace.num_tile_rows(xs)):
            row = trace.load(xs.tiles[t, :])
            trace.store(ys.tiles[t, :], fn(row))
    return ir


ROW_WIDTH, ROWS_TILE, COLS_TILE = 2, 2, 4
STATED = {"error": 2e-3, "over": (-math.inf, 0.0)}


def vector_bodies():
    """{name: (unit program, Dst tiles the inputs are copied to)} of every body."""
    streams = {
        "add": (2, lambda a, b: a + b),
        "mul": (2, lambda a, b: a * b),
        "exp": (1, trace.exp),
        "exp2": (1, trace.exp2),
        "exp2_flash": (1, lambda a: trace.exp2(a, **STATED)),
        "recip": (1, trace.reciprocal),
        "rsqrt": (1, trace.rsqrt),
        "sqrt": (1, trace.sqrt),
        "tanh": (1, trace.tanh),
        "sigmoid": (1, trace.sigmoid),
        "silu": (1, trace.silu),
        "erf": (1, trace.erf),
        "maximum": (2, trace.maximum),
        "where": (2, lambda a, b: trace.where(a > b, a, b)),
        "square": (1, trace.square),
    }
    out = {}
    for name, (inputs, fn) in streams.items():
        out[name] = (unit_program(stream("vec", inputs, fn)), list(range(inputs)))
    rows = {
        "rowsum": lambda row: row * 0.0 + trace.reduce_sum(row, exact=True).col(),
        "rowmax": lambda row: row * 0.0 + trace.reduce_max(row, exact=True).col(),
    }
    for name, fn in rows.items():
        unit = row_program(row_ir("vec", fn), ROW_WIDTH, ROWS_TILE, COLS_TILE)
        out[name] = (unit, [0, 1, ROWS_TILE, COLS_TILE])
    return out


def write_vector_headers(bodies):
    """generated/<name>/vec.hpp: the body's header, whose function is km_tile::vec."""
    costs = {}
    for name, (unit, _) in bodies.items():
        folder = GENERATED / name
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "vec.hpp").write_text(emit(unit))
        costs[name] = unit.cost("math")[1]
    (GENERATED / "costs.json").write_text(json.dumps(costs))
    return costs


# ---------------------------------------------------------------- the sections


def section(name, **fields):
    base = dict(
        mode=0,
        tiles=32,
        group=1,
        copy=1,
        pack=1,
        vec=None,
        a="bf16",
        b="bf16",
        alt="bf16",
        out="bf16",
        out_alt="bf16",
        dest32=True,
        fidelity="HiFi4",
        rt=1,
        ct=1,
        kt=1,
        d2d=False,
        reconf_unpack=0,
        reconf_pack=0,
        repeats=5,
        note="",
    )
    base.update(fields)
    return name, base


def sections():
    """The named sections of the cost table, in the order they are listed."""
    out = dict(
        [
            section("sync", copy=0, pack=0, tiles=64),
            section("sync_pack", copy=0, pack=1, tiles=64),
        ]
    )
    for fmt in FORMATS:
        for g in (1, 4):
            out.update(
                [
                    section(f"copy_{fmt}_g{g}", a=fmt, out=fmt, group=g),
                    section(f"unpack_{fmt}_g{g}", a=fmt, out=fmt, group=g, pack=0),
                    section(f"pack_{fmt}_g{g}", a=fmt, out=fmt, group=g, copy=0),
                ]
            )
    for g in (1, 4):
        out.update(
            [
                section(f"copy_fp32d_g{g}", a="fp32", out="fp32", group=g, d2d=True),
                section(
                    f"unpack_fp32d_g{g}",
                    a="fp32",
                    out="fp32",
                    group=g,
                    d2d=True,
                    pack=0,
                ),
            ]
        )
    for a, o in (
        ("bf16", "fp32"),
        ("fp32", "bf16"),
        ("bf16", "bfp8_b"),
        ("bfp8_b", "bf16"),
        ("bf16", "bfp4_b"),
        ("bfp4_b", "bf16"),
    ):
        out.update([section(f"copy_{a}_to_{o}_g4", a=a, out=o, group=4)])
    for fid in ("LoFi", "HiFi2", "HiFi4"):
        for shape in ((1, 1, 1), (1, 1, 4), (2, 2, 4)):
            rt, ct, kt = shape
            out.update(
                [
                    section(
                        f"mm_{fid}_{rt}x{ct}x{kt}",
                        mode=1,
                        fidelity=fid,
                        rt=rt,
                        ct=ct,
                        kt=kt,
                        tiles=max(16, 2 * rt * kt, 2 * kt * ct),
                        group=1,
                    )
                ]
            )
    for a, b in (("bf16", "bfp8_b"), ("bf16", "bfp4_b"), ("bfp8_b", "bfp8_b")):
        out.update(
            [
                section(
                    f"mm_HiFi2_1x1x4_{a}_{b}",
                    mode=1,
                    fidelity="HiFi2",
                    kt=4,
                    a=a,
                    b=b,
                    tiles=16,
                )
            ]
        )
    out.update(
        [
            section(
                "clock100", mode=4, tiles=100, repeats=1, note="a 100 M cycle spin"
            ),
            section("clock", mode=4, tiles=300, repeats=1, note="a 300 M cycle spin"),
            section("reconf_none", mode=2, tiles=32),
            section("reconf_unpack_same", mode=2, tiles=32, reconf_unpack=1),
            section("reconf_pack_same", mode=2, tiles=32, reconf_pack=1),
            section(
                "reconf_both_same", mode=2, tiles=32, reconf_unpack=1, reconf_pack=1
            ),
            section(
                "reconf_both_bf16_bfp8",
                mode=2,
                tiles=32,
                alt="bfp8_b",
                out_alt="bfp8_b",
                reconf_unpack=1,
                reconf_pack=1,
            ),
            section(
                "reconf_both_bf16_fp32",
                mode=2,
                tiles=32,
                alt="fp32",
                out_alt="fp32",
                reconf_unpack=1,
                reconf_pack=1,
            ),
        ]
    )
    return out


def vec_bf16_sections(names):
    """Each body on bf16 tiles that go through SrcA (the copy of 45 cycles a tile)."""
    return {
        f"vecb_{name}": section(
            f"vecb_{name}",
            vec=name,
            a="bf16",
            out="bf16",
            note="bf16 through SrcA",
        )[1]
        for name in names
    }


def vec_sections(names):
    """Each body on fp32 tiles unpacked straight to Dst, as the tile streams do."""
    out = {}
    for name in names:
        out.update(
            [
                section(
                    f"vec_{name}",
                    vec=name,
                    a="fp32",
                    out="fp32",
                    d2d=True,
                    note="fp32 Dst",
                )
            ]
        )
    return out


# ---------------------------------------------------------------- the launch


def aiclk_mhz():
    card = os.environ.get("TT_VISIBLE_DEVICES", "0").split(",")[0]
    try:
        with open(f"/sys/class/tenstorrent/tenstorrent!{card}/tt_aiclk") as f:
            return int(f.read().strip())
    except (OSError, ValueError):
        return None


def tile_data(count, seed):
    """`count` tiles of values in [0.5, 1.5) as [32 count, 32] float32."""
    rng = np.random.default_rng(seed)
    return rng.uniform(0.5, 1.5, (32 * count, 32)).astype(np.float32)


def launch(session, name, cfg, dsts=None):
    """One program on core (0, 0): the section `name`; returns (Launch, info tensor,
    nonce)."""
    mode, n = cfg["mode"], cfg["tiles"]
    fmt = lambda key: FORMATS[cfg[key]]  # noqa: E731
    pages_a = 1 if mode == 4 else (n // 2 if mode == 2 else n)
    pages_b = n if mode == 1 else 1
    pages_alt = n // 2 if mode == 2 else 1
    tensors = []
    for key, pages, seed in (
        ("a", pages_a, 1),
        ("b", pages_b, 2),
        ("alt", pages_alt, 3),
    ):
        tensors.append(
            session.tensor(tile_data(pages, seed), FORMATS[cfg[key]][0], "tile")
        )
    t_info = session.tensor(np.zeros((1, TILE_WORDS), np.uint32), "uint32")
    core = [(0, 0, 0, 0)]
    nonce = secrets.randbits(32) | 1
    run = session.launch()
    run.cb(core, CB_A, fmt("a")[0], fmt("a")[1], pages_a * fmt("a")[1])
    if mode == 1:
        run.cb(core, CB_B, fmt("b")[0], fmt("b")[1], pages_b * fmt("b")[1])
    if mode == 2:
        run.cb(core, CB_ALT, fmt("alt")[0], fmt("alt")[1], pages_alt * fmt("alt")[1])
    if mode == 4:
        out_pages = 1
    elif mode == 0:
        out_pages = n
    elif mode == 1:
        out_pages = cfg["rt"] * cfg["ct"] * (n // cfg["group"])
    else:
        out_pages = n // 2
    run.cb(core, CB_OUT, fmt("out")[0], fmt("out")[1], out_pages * fmt("out")[1])
    if mode == 2:
        run.cb(
            core,
            CB_OUT_ALT,
            fmt("out_alt")[0],
            fmt("out_alt")[1],
            out_pages * fmt("out_alt")[1],
        )
    run.cb(core, CB_INFO, "float32", 4 * TILE_WORDS, 4 * TILE_WORDS)
    accessors = [w for t in tensors for w in t.accessor_args()]
    words = [t.address for t in tensors] + [pages_a, pages_b if mode == 1 else 0]
    words += [pages_alt if mode == 2 else 0]
    run.kernel(str(KERNELS / "reader.cpp"), core, 1, accessors, [], [], [(0, 0, words)])
    run.kernel(
        str(KERNELS / "writer.cpp"),
        core,
        0,
        t_info.accessor_args(),
        [],
        [],
        [(0, 0, [t_info.address])],
    )
    defines = {
        "PB_MODE": mode,
        "PB_TILES": n,
        "PB_GROUP": cfg["group"],
        "PB_COPY": cfg["copy"],
        "PB_PACK": cfg["pack"],
        "PB_VEC": int(cfg["vec"] is not None),
        "PB_VEC_DSTS": ", ".join(str(d) for d in (dsts or [0])),
        "PB_RT": cfg["rt"],
        "PB_CT": cfg["ct"],
        "PB_KT": cfg["kt"],
        "PB_RECONF_UNPACK": cfg["reconf_unpack"],
        "PB_RECONF_PACK": cfg["reconf_pack"],
    }
    headers = [str(GENERATED)]
    if cfg["vec"]:
        headers.insert(0, str(GENERATED / cfg["vec"]))
    options = {
        "math_fidelity": cfg["fidelity"],
        "fp32_dest_acc_en": cfg["dest32"],
    }
    if cfg["d2d"]:
        options["unpack_to_dest_mode"] = {CB_A: "UnpackToDestFp32"}
    run.kernel(
        str(KERNELS / "compute.cpp"),
        core,
        2,
        [],
        [(k, str(v)) for k, v in defines.items()],
        headers,
        [(0, 0, [nonce, cfg["repeats"]])],
        **several.compute_config(options),
    )
    return run, t_info, nonce


# ---------------------------------------------------------------- reading a result


def decode(info, cfg, tables):
    """Per repeat: each CPU's span (less the empty span), the window, the counters."""
    info = np.asarray(info).reshape(-1).astype(np.int64)
    empty = int(statistics.median(info[SYNC : SYNC + SYNCS]))
    names = [name for t in tables for name, _ in t]
    repeats = []
    for r in range(cfg["repeats"]):
        base = REP + r * REP_STRIDE
        s = [int(x) & 0xFFFFFFFF for x in info[base : base + 6]]
        start = min(s[0], s[2], s[4])
        row = {
            "unpack": (s[1] - s[0]) - empty,
            "math": (s[3] - s[2]) - empty,
            "pack": (s[5] - s[4]) - empty,
            "window": max(s[1], s[3], s[5]) - start,
            "start_offsets": [s[0] - start, s[2] - start, s[4] - start],
            "end_offsets": [s[1] - start, s[3] - start, s[5] - start],
            "refs": [int(x) for x in info[base + REFS : base + REFS + 4]],
            "read_time": int(info[base + READ_TIME]),
        }
        values = info[base + COUNTERS : base + COUNTERS + len(names)]
        row["counters"] = {n: int(v) for n, v in zip(names, values)}
        repeats.append(row)
    return {
        "empty": empty,
        "throttle_word": int(info[THROTTLE]),
        "dbg_feature_disable": int(info[DBG_DISABLE]),
        "failed": [int(x) for x in info[FAIL : FAIL + 3]],
        "repeats": repeats,
    }


KEY_COUNTERS = (
    "FPU_COUNTER",
    "SFPU_COUNTER",
    "MATH_COUNTER",
    "UNPACK0_BUSY_THREAD0",
    "UNPACK1_BUSY_THREAD0",
    "PACKER_BUSY",
    "PACKER0_DEST_READ_REQ",
    "THREAD_STALLS_0",
    "THREAD_STALLS_1",
    "THREAD_STALLS_2",
    "THREAD_INSTRUCTIONS_0",
    "THREAD_INSTRUCTIONS_1",
    "THREAD_INSTRUCTIONS_2",
)


def summary(name, cfg, got, clock):
    """One line: medians (and range) over the repeats, a tile of cfg['tiles'] units."""
    reps = got["repeats"]

    def med(key):
        vals = [r[key] for r in reps]
        return [statistics.median(vals), min(vals), max(vals)]

    line = {
        "section": name,
        "tiles": cfg["tiles"],
        "aiclk_mhz": clock,
        "empty": got["empty"],
        "throttle_word": got["throttle_word"],
        "window": med("window"),
        "unpack": med("unpack"),
        "math": med("math"),
        "pack": med("pack"),
        "start_offsets": reps[-1]["start_offsets"],
        "end_offsets": reps[-1]["end_offsets"],
        "refs": reps[-1]["refs"],
        "counters": {
            k: statistics.median([r["counters"][k] for r in reps]) for k in KEY_COUNTERS
        },
    }
    return line


# ---------------------------------------------------------------- build and card


def chosen(args):
    bodies = vector_bodies()
    every = sections()
    every.update(vec_sections(bodies))
    every.update(vec_bf16_sections(bodies))
    names = args.only or list(every)
    missing = [n for n in names if n not in every]
    if missing:
        sys.exit(f"no such section: {missing}")
    return bodies, every, names


def build(args):
    tree = native.metal_tree()
    os.environ["TT_METAL_MOCK_CLUSTER_DESC_PATH"] = str(tree / DESCRIPTOR)
    os.environ["TT_METAL_CACHE"] = str(JIT_CACHE)
    tables = counter_tables(tree)
    write_counters_header(tables)
    bodies, every, names = chosen(args)
    log(f"estimates (vector unit, cycles) {json.dumps(write_vector_headers(bodies))}")
    sizes = {}
    with km.Session() as session:
        for name in names:
            cfg = every[name]
            dsts = bodies[cfg["vec"]][1] if cfg["vec"] else None
            started = time.time()
            run, *_ = launch(session, name, cfg, dsts)
            _, *built = run.build()
            got = session_kernels.kernel_sizes(built)
            sizes[name] = [got.total, got.limit, got.text]
            log(
                f"built {name}: {got.total} of {got.limit} B, "
                f"{time.time() - started:.1f} s"
            )
    # the host side on a made-up result: a zero page decodes
    fake = np.zeros(TILE_WORDS, np.uint32)
    fake[SYNC : SYNC + SYNCS] = 10
    name = names[0]
    log(json.dumps(summary(name, every[name], decode(fake, every[name], tables), None)))
    print(json.dumps({"kernel_buffer": sizes}), flush=True)
    return 0


def card(args):
    tree = native.metal_tree()
    os.environ["TT_METAL_CACHE"] = str(JIT_CACHE)
    tables = counter_tables(tree)
    bodies, every, names = chosen(args)
    log(f"kernels from the build's cache {JIT_CACHE}")
    with open("/proc/loadavg") as f:
        load = f.read().split()[:3]
    clock_before = aiclk_mhz()
    log(f"aiclk {clock_before} MHz, load {load}")
    raw = {}
    with km.Session() as session:
        for name in names:
            cfg = every[name]
            dsts = bodies[cfg["vec"]][1] if cfg["vec"] else None
            log(f"launch {name}")
            run, t_info, nonce = launch(session, name, cfg, dsts)
            samples, stop = [], threading.Event()
            if cfg["mode"] == 4:  # the card's clock while the spin runs

                def poll(stop=stop, samples=samples):
                    while not stop.is_set():
                        samples.append(aiclk_mhz())
                        stop.wait(0.025)

                threading.Thread(target=poll, daemon=True).start()
            began = time.time()
            run.run()
            session.device.finish()
            elapsed = time.time() - began
            stop.set()
            if cfg["mode"] == 4:
                seen = [s for s in samples if s]
                cycles = cfg["tiles"] * 1e6
                log(
                    f"clock: {cycles:.0f} wall-clock cycles in {elapsed:.4f} s host "
                    f"time (command included) = {cycles / elapsed / 1e6:.1f} MHz; "
                    f"sysfs aiclk while it ran: {len(seen)} samples, "
                    f"min {min(seen, default=None)} median "
                    f"{statistics.median(seen) if seen else None} "
                    f"max {max(seen, default=None)}"
                )
            info = t_info.read().reshape(-1).copy()
            if int(info[NONCE]) != nonce:
                log(f"{name}: the nonce is not the run's: {int(info[NONCE])} / {nonce}")
                continue
            got = decode(info, cfg, tables)
            if any(got["failed"]):
                log(f"{name}: a CPU gave up a barrier at tag {got['failed']}")
            raw[name] = got
            print(json.dumps(summary(name, cfg, got, aiclk_mhz())), flush=True)
    if args.save:
        Path(args.save).write_text(
            json.dumps({"aiclk_before": clock_before, "raw": raw})
        )
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("build", "card", "list"))
    parser.add_argument("--only", nargs="*", help="section names (probe.py list)")
    parser.add_argument("--save", help="the raw per-repeat results as JSON")
    args = parser.parse_args()
    if args.command == "list":
        every = sections()
        every.update(vec_sections(vector_bodies()))
        every.update(vec_bf16_sections(vector_bodies()))
        print("\n".join(every))
        return 0
    return {"build": build, "card": card}[args.command](args)


if __name__ == "__main__":
    sys.exit(main())
